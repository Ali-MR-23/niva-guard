<?php

if (!defined('ABSPATH')) {
    exit;
}

/**
 * Setup: the optional early loader (mu-plugin), the text log file and the report built from it.
 */
class NIVAWPG_Setup {

    public const LOADER_VERSION = '3';
    public const MAX_LOG = 2097152; // 2 MB

    /* ───────────── mu-plugin loader ───────────── */

    public static function loader_path(): string {
        $dir = defined('WPMU_PLUGIN_DIR') ? WPMU_PLUGIN_DIR : WP_CONTENT_DIR . '/mu-plugins';

        return rtrim($dir, '/\\') . '/niva-guard-loader.php';
    }

    private static function loader_code(): string {
        return "<?php\n"
            . "/**\n * NIVA Guard loader (auto-generated, v" . self::LOADER_VERSION . ")\n"
            . " * Generated by the NIVA Guard plugin so that it loads before the other plugins.\n"
            . " * Removed automatically when the plugin is deactivated or deleted.\n */\n"
            . "if (!defined('ABSPATH')) { exit; }\n"
            . "if (!defined('NIVAWPG_VERSION')) {\n"
            . "    \$nivawpg_active = (array) get_option('active_plugins', []);\n"
            . "    \$nivawpg_main = WP_PLUGIN_DIR . '/niva-guard/niva-guard.php';\n"
            . "    if (in_array('niva-guard/niva-guard.php', \$nivawpg_active, true) && file_exists(\$nivawpg_main)) {\n"
            . "        require_once \$nivawpg_main;\n"
            . "    }\n"
            . "}\n";
    }

    /** Removes the loader and moves the log folder of the legacy name (NIVA HTTP Guard). */
    public static function drop_legacy(): void {
        $mu = (defined('WPMU_PLUGIN_DIR') ? WPMU_PLUGIN_DIR : WP_CONTENT_DIR . '/mu-plugins') . '/niva-http-guard-loader.php';

        if (is_file($mu)) {
            wp_delete_file($mu);
        }

        $old_loader = dirname($mu) . '/niva-wp-guard-loader.php';

        if (is_file($old_loader)) {
            wp_delete_file($old_loader);
        }

        $up = wp_upload_dir(null, false);
        $base = rtrim(!empty($up['basedir']) && is_dir($up['basedir']) ? $up['basedir'] : WP_CONTENT_DIR, '/\\');

        if (is_dir($base . '/niva-http-guard') && !is_dir($base . '/niva-wp-guard')) {
            NIVAWPG_Fs::move($base . '/niva-http-guard', $base . '/niva-wp-guard');
        }
    }

    /** @return array{ok:bool,message:string} */
    public static function install_loader(): array {
        self::drop_legacy();        $path = self::loader_path();
        $dir = dirname($path);

        if (!is_dir($dir) && !wp_mkdir_p($dir)) {
            return ['ok' => false, 'message' => sprintf(/* translators: %s: folder path */ __('The mu-plugins folder could not be created: %s', 'niva-guard'), $dir)];
        }

        if (!NIVAWPG_Fs::writable($dir)) {
            return ['ok' => false, 'message' => __('The mu-plugins folder is not writable; the plugin works normally but loads later than the others.', 'niva-guard')];
        }

        if (!NIVAWPG_Fs::put($path, self::loader_code())) {
            return ['ok' => false, 'message' => __('Writing the loader file failed.', 'niva-guard')];
        }

        return ['ok' => true, 'message' => sprintf(/* translators: %s: file path */ __('Loader installed: %s', 'niva-guard'), $path)];
    }

    public static function remove_loader(): void {
        $path = self::loader_path();

        if (is_file($path)) {
            wp_delete_file($path);
        }
    }

    /** Loader state: installed | missing | outdated | unwritable */
    public static function loader_status(): string {
        $path = self::loader_path();

        if (is_file($path)) {
            return strpos(NIVAWPG_Fs::get($path), 'auto-generated, v' . self::LOADER_VERSION) !== false ? 'installed' : 'outdated';
        }

        return NIVAWPG_Fs::writable(dirname($path)) || (!is_dir(dirname($path)) && NIVAWPG_Fs::writable(WP_CONTENT_DIR)) ? 'missing' : 'unwritable';
    }

    /** Recreates the loader after an update (only when the user turned it on). */
    public static function self_heal(): void {
        if (empty(NIVAWPG_Settings::get()['loader_on'])) {
            return; // Without the user's consent no file is created outside the plugin folder
        }

        if (in_array(self::loader_status(), ['missing', 'outdated'], true)) {
            self::install_loader();
        }
    }

    /* ───────────── Text log file ───────────── */

    public static function log_dir(): string {
        $up = wp_upload_dir(null, false);
        $base = !empty($up['basedir']) && is_dir($up['basedir']) ? $up['basedir'] : WP_CONTENT_DIR;

        return rtrim($base, '/\\') . '/niva-wp-guard';
    }

    public static function log_path(): string {
        $secret = substr(md5((defined('AUTH_KEY') ? AUTH_KEY : '') . ABSPATH . 'nhg'), 0, 10);

        return self::log_dir() . '/http-log-' . $secret . '.txt';
    }

    /** Creates the log folder and blocks direct web access to it. */
    public static function ensure_log_dir(): bool {
        $dir = self::log_dir();

        if (!is_dir($dir) && !wp_mkdir_p($dir)) {
            return false;
        }

        if (!is_file($dir . '/.htaccess')) {
            NIVAWPG_Fs::put($dir . '/.htaccess', "Order allow,deny\nDeny from all\n<IfModule mod_authz_core.c>\nRequire all denied\n</IfModule>\n");
        }

        if (!is_file($dir . '/index.php')) {
            NIVAWPG_Fs::put($dir . '/index.php', "<?php // Silence is golden.\n");
        }

        return NIVAWPG_Fs::writable($dir);
    }

    /** @param string[] $lines */
    public static function append_log(array $lines): void {
        if (!$lines || !self::ensure_log_dir()) {
            return;
        }

        $path = self::log_path();

        if (is_file($path) && filesize($path) > self::MAX_LOG) {
            NIVAWPG_Fs::move($path, $path . '.old'); // Log rotation; only one previous copy is kept
        }

        // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents -- appending to the log (FILE_APPEND with a lock) is not available in WP_Filesystem
        file_put_contents($path, implode("\n", $lines) . "\n", FILE_APPEND | LOCK_EX);
    }

    public static function clear_log(): void {
        foreach ([self::log_path(), self::log_path() . '.old'] as $f) {
            if (is_file($f)) {
                wp_delete_file($f);
            }
        }
    }

    /* ───────────── Report from the text file ───────────── */

    /**
     * Reads the log file and builds a summary.
     * @return array{exists:bool,size:int,starts:int,slow:int,wait:float,errors:int,rows:array,plugins:array}
     */
    public static function report(): array {
        $path = self::log_path();
        $out = ['exists' => is_file($path), 'size' => 0, 'starts' => 0, 'slow' => 0, 'wait' => 0.0, 'errors' => 0, 'rows' => [], 'plugins' => []];

        if (!$out['exists']) {
            return $out;
        }

        $out['size'] = (int) filesize($path);
        $raw = NIVAWPG_Fs::get($path);
        $map = []; // host/path ⇒ plugin
        $agg = [];

        foreach (preg_split('/\R/u', $raw) as $line) {
            if (preg_match('/^[\d-]+ [\d:]+ \| (?!SLOW)([^|]+?) \| (\w+) \| (\w+) \| (.+?) \| start$/', $line, $m)) {
                $out['starts']++;
                $map[$m[4]] = trim($m[1]);
            } elseif (preg_match('/^[\d-]+ [\d:]+ \| SLOW ([\d.]+)s \| ([^|]*?) \| (.+)$/', $line, $m)) {
                $sec = (float) $m[1];
                $hp = trim($m[3]);
                $a = $agg[$hp] ?? ['hp' => $hp, 'n' => 0, 'total' => 0.0, 'max' => 0.0, 'err' => 0];
                $a['n']++;
                $a['total'] += $sec;
                $a['max'] = max($a['max'], $sec);
                if (in_array(trim($m[2]), ['ERROR', ''], true)) {
                    $a['err']++;
                    $out['errors']++;
                }

                $agg[$hp] = $a;
                $out['slow']++;
                $out['wait'] += $sec;
            }
        }

        foreach ($agg as $hp => $a) {
            $a['plugin'] = $map[$hp] ?? '—';
            $out['rows'][] = $a;
            $out['plugins'][$a['plugin']] = ($out['plugins'][$a['plugin']] ?? 0.0) + $a['total'];
        }

        usort($out['rows'], static fn($x, $y) => $y['total'] <=> $x['total']);
        arsort($out['plugins']);

        return $out;
    }

    /** Plain-text summary report to copy and send. */
    public static function report_text(): string {
        $r = self::report();
        $lines = [];
        $lines[] = __('NIVA Guard — connection report', 'niva-guard');
        $lines[] = sprintf(/* translators: 1: site URL, 2: date and time, 3: plugin version */ __('Site: %1$s | Date: %2$s UTC | Version: %3$s', 'niva-guard'), home_url(), gmdate('Y-m-d H:i'), NIVAWPG_VERSION);

        if (!$r['exists']) {
            $lines[] = __('The log file has not been created yet.', 'niva-guard');

            return implode("\n", $lines);
        }

        $lines[] = sprintf(/* translators: 1: unique connections, 2: slow connections, 3: total wait in seconds, 4: errors */ __('Unique connections: %1$d | Slow connections (over 0.5 s): %2$d | Total wait: %3$.1f s | Errors / no response: %4$d', 'niva-guard'), $r['starts'], $r['slow'], $r['wait'], $r['errors']);
        $lines[] = '';
        $lines[] = __('— By plugin (total wait time):', 'niva-guard');

        foreach (array_slice($r['plugins'], 0, 12, true) as $p => $t) {
            $lines[] = sprintf('  %-34s %.1f s', $p, $t);
        }

        $lines[] = '';
        $lines[] = __('— Slowest addresses:', 'niva-guard');

        foreach (array_slice($r['rows'], 0, 20) as $row) {
            $lines[] = sprintf(/* translators: 1: address, 2: number of requests, 3: total seconds, 4: longest seconds, 5: errors, 6: plugin */ __('  %1$-60s  %2$d times  total %3$.1fs  max %4$.1fs  errors:%5$d  [%6$s]', 'niva-guard'), $row['hp'], $row['n'], $row['total'], $row['max'], $row['err'], $row['plugin']);
        }

        return implode("\n", $lines);
    }
}
